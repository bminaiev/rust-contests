#[allow(unused)]
use algo_lib::dbg;
use algo_lib::io::input::Input;
use algo_lib::io::output::Output;

fn solve(input: &mut Input, out: &mut Output) {
    let tc = input.usize();
    for _ in 0..tc {
        let n = input.usize();
        let m = input.usize();
        assert_eq!(m, 0);
        let mut cnt = (n + 1) / 2;
        if n == 1 {
            cnt = 0;
        }
        out.println(cnt);
        for i in 0..cnt {
            let rr = vec![i + 1, i + cnt];
            out.println(rr);
        }
    }
}

pub(crate) fn run(mut input: Input, mut output: Output) -> bool {
    solve(&mut input, &mut output);
    output.flush();
    true
}

