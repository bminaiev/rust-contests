#[allow(unused)]
use algo_lib::dbg;
use algo_lib::io::input::Input;
use algo_lib::io::output::Output;

fn solve(input: &mut Input, out: &mut Output) {
    let tc = input.usize();
    for _ in 0..tc {
        let mut x = input.i32();
        let mut res = 0;
        while x != 0 {
            res += 1;
            let first_digit = x.to_string().chars().next().unwrap().to_digit(10).unwrap() as i32;
            x -= first_digit;
        }
        out.println(res);
    }
}

pub(crate) fn run(mut input: Input, mut output: Output) -> bool {
    solve(&mut input, &mut output);
    output.flush();
    true
}

