fn solve(input: &mut Input, out: &mut Output) {
    let n = input.usize();
    let m = input.usize();
    out.println(Mod::new(prec[n][m]) * Mod::TWO);
}

fn stress() {
    let mut nprec = [[0; N]; N];
    for i in 1..N {
        dbg!(i);
        for j in i..N {
            let mut res = solve_case(i, j);
            nprec[i][j] = res.value();
            nprec[j][i] = res.value();
        }
    }
    dbg!(nprec);
}

pub(crate) fn run(mut input: Input, mut output: Output) -> bool {
    solve(&mut input, &mut output);
    output.flush();
    true
}

