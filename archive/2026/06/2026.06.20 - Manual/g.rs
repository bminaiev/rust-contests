type Mod = Mod_998_244_353;

fn solve_case(n: usize, m: usize) -> Mod {
    if n < m {
        return solve_case(m, n);
    }
    let mut dp = vec![Mod::ZERO; 1 << m];
    let mut ndp = vec![Mod::ZERO; 1 << m];
    dp[0] = Mod::ONE;
    for i in 0..n {
        for j in 0..m {
            for mask in 0..(1 << m) {
                let ways = dp[mask];
                if ways == Mod::ZERO {
                    continue;
                }
                for nbit in 0..2 {
                    let set_bit = 1 << j;
                    let mut nmask = mask & (!set_bit);
                    if nbit == 1 {
                        nmask |= set_bit;
                    }
                    if (i + j) % 2 == 0 {
                        // 1 or 3
                        if nbit == 0 {
                            if i > 0 && (mask >> j) & 1 == 1 {
                                continue;
                            }
                            if j > 0 && (mask >> (j - 1)) & 1 == 1 {
                                continue;
                            }
                        }
                    } else {
                        // 2 or 4
                        if nbit == 1 {
                            if i > 0 && (mask >> j) & 1 == 0 {
                                continue;
                            }
                            if j > 0 && (mask >> (j - 1)) & 1 == 0 {
                                continue;
                            }
                        }
                    }
                    ndp[nmask] += ways;
                }
            }
            std::mem::swap(&mut dp, &mut ndp);
            ndp.fill(Mod::ZERO);
        }
    }
    let mut res = Mod::ZERO;
    for mask in 0..(1 << m) {
        res += dp[mask];
    }
    res
}

